export const GLYPH_W = 5;
export const GLYPH_H = 7;
/** Columns one character occupies, including the blank column after it. */
export const CELL_W = GLYPH_W + 1;
/** Rows one text line occupies, including the blank row beneath it. */
export const CELL_H = GLYPH_H + 2;

/**
 * Rasterises text lines into a flat LED bitmap, `cols` characters wide.
 * Lines are centred; anything past `cols` characters is clipped.
 */
export function rasterise(lines: string[], cols: number): { width: number; height: number; cells: Uint8Array } {
  const width = cols * CELL_W + 1;
  const height = lines.length * CELL_H + 1;
  const cells = new Uint8Array(width * height);

  lines.forEach((raw, lineIndex) => {
    const text = raw.toUpperCase().slice(0, cols);
    const pad = Math.floor((cols - text.length) / 2);
    [...text].forEach((ch, i) => {
      const glyph = GLYPHS[ch] ?? GLYPHS[' '];
      const x0 = 1 + (pad + i) * CELL_W;
      const y0 = 1 + lineIndex * CELL_H;
      for (let y = 0; y < GLYPH_H; y++) {
        for (let x = 0; x < GLYPH_W; x++) {
          if (glyph[y][x] === '#') cells[(y0 + y) * width + x0 + x] = 1;
        }
      }
    });
  });

  return { width, height, cells };
}
